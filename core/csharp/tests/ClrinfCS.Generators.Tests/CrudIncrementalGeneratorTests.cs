using System;
using System.Linq;
using ClrinfCS.Generators;
using Microsoft.CodeAnalysis;
using Xunit;

namespace ClrinfCS.Generators.Tests;

public class CrudIncrementalGeneratorTests
{
    private const string EntitySource = """
        using ClrinfCS.Core;

        namespace Shop.Domain;

        [GenerateCrudEndpoints]
        public class Category
        {
            public int Id { get; set; }
            public string Name { get; set; } = string.Empty;
            public string? Description { get; set; }
            [CrudIgnore] public string InternalCode { get; set; } = string.Empty;
        }
        """;

    private const string MediatorStubs = """
        namespace Mediator.Net.Contracts;

        public interface IRequest<TResponse> { }

        public interface IReceiveContext<TRequest>
        {
            TRequest Message { get; }
        }

        public interface IRequestHandler<TRequest, TResponse>
        {
            System.Threading.Tasks.Task<TResponse> Handle(
                IReceiveContext<TRequest> context,
                System.Threading.CancellationToken cancellationToken);
        }

        public interface IMediator
        {
            System.Threading.Tasks.Task<TResponse> RequestAsync<TRequest, TResponse>(
                TRequest request,
                System.Threading.CancellationToken cancellationToken = default);
        }
        """;

    [Fact]
    public void GeneratesNativeHandlerAndEndpointForEveryOperation()
    {
        var (_, output, result, diagnostics, _) = GeneratorTestHarness.Run(EntitySource);
        Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error);
        Assert.DoesNotContain(output.GetDiagnostics(), d => d.Severity == DiagnosticSeverity.Error);

        var hintNames = result.GeneratedTrees.Select(t => t.FilePath).ToArray();
        foreach (var operation in new[] { "Create", "Update", "Delete", "GetById", "GetList" })
        {
            Assert.Contains(hintNames, n => n.Contains($".Crud.{operation}.Handler.g.cs"));
            Assert.Contains(hintNames, n => n.Contains($".Crud.{operation}.Endpoint.g.cs"));
        }

        var deleteHandler = TreeText(result, "Crud.Delete.Handler.g.cs");
        Assert.Contains("RunBeforeDeleteAsync", deleteHandler);
        Assert.Contains("RunBeforeDeleteAsync(_rules, entity", deleteHandler);

        var createHandler = TreeText(result, "Crud.Create.Handler.g.cs");
        Assert.Contains("RunBeforeCreateAsync", createHandler);
        Assert.DoesNotContain("InternalCode", createHandler);
        Assert.DoesNotContain("Id = request.Id", createHandler);

        var endpoint = TreeText(result, "Crud.Create.Endpoint.g.cs");
        Assert.Contains("MapPost", endpoint);
        Assert.Contains("(RequestDelegate)", endpoint);
        Assert.Contains("ReadJsonAsync", endpoint);
        Assert.Contains("ToJsonBytes", endpoint);
        Assert.Contains("Results.Created", endpoint);
        Assert.Contains("Accepts<CreateCategoryRequest>", endpoint);

        var models = TreeText(result, "Crud.Models.g.cs");
        Assert.Contains("Utf8JsonWriter", models);
        Assert.Contains("ToJsonBytes(CategoryDto", models);
        Assert.Contains("ToJsonBytes(PagedResult<CategoryDto>", models);

        var central = TreeText(result, "GeneratedCrudExtensions.g.cs");
        Assert.Contains("MapGeneratedCrudEndpoints", central);
        Assert.Contains("AddGeneratedCrud", central);
    }

    [Fact]
    public void EjectedOperationCompilesWithoutGeneratorReEmittingIt()
    {
        var (_, _, initialResult, _, _) = GeneratorTestHarness.Run(EntitySource);
        var ejectedHandler = TreeText(initialResult, "Crud.Create.Handler.g.cs")
            .Replace("// <auto-generated />", "// Ejected");
        var ejectedEndpoint = TreeText(initialResult, "Crud.Create.Endpoint.g.cs")
            .Replace("// <auto-generated />", "// Ejected");

        var updatedEntitySource = EntitySource.Replace(
            "[GenerateCrudEndpoints]",
            "[GenerateCrudEndpoints(Operations = CrudOperations.All & ~CrudOperations.Create)]");

        var (_, output, result, diagnostics, _) = GeneratorTestHarness.Run(
            updatedEntitySource,
            additionalSources: ejectedHandler,
            extraTrees: ejectedEndpoint);

        Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error);
        Assert.DoesNotContain(output.GetDiagnostics(), d => d.Severity == DiagnosticSeverity.Error);
        Assert.DoesNotContain(result.GeneratedTrees, t => t.FilePath.Contains(".Crud.Create.Handler.g.cs"));
        Assert.DoesNotContain(result.GeneratedTrees, t => t.FilePath.Contains(".Crud.Create.Endpoint.g.cs"));
    }

    [Fact]
    public void UsesMediatorNetOnlyWhenSelected()
    {
        var (_, output, result, diagnostics, _) = GeneratorTestHarness.Run(
            EntitySource, dispatcherProperty: "mediatornet", additionalSources: MediatorStubs);

        Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error);
        Assert.DoesNotContain(output.GetDiagnostics(), d => d.Severity == DiagnosticSeverity.Error);

        var handler = TreeText(result, "Crud.Create.Handler.g.cs");
        Assert.Contains("MediatorNet.IRequestHandler", handler);
        Assert.Contains("MediatorNet.IRequest<", handler);
        Assert.Contains("RequestContext Context", handler);

        var endpoint = TreeText(result, "Crud.Create.Endpoint.g.cs");
        Assert.Contains("mediator.RequestAsync", endpoint);
    }

    [Fact]
    public void AttributeDispatcherWinsOverBuildProperty()
    {
        var source = EntitySource.Replace(
            "[GenerateCrudEndpoints]",
            "[GenerateCrudEndpoints(Dispatcher = CrudDispatcher.Native)]");

        var (_, _, result, diagnostics, _) = GeneratorTestHarness.Run(
            source, dispatcherProperty: "mediatornet", additionalSources: MediatorStubs);

        Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error);
        var handler = TreeText(result, "Crud.Create.Handler.g.cs");
        Assert.DoesNotContain("IRequestHandler", handler);
        Assert.Contains("ICrudStore<", handler);
    }

    [Fact]
    public void DefaultsToNativeWhenNothingIsConfigured()
    {
        var (_, _, result, diagnostics, _) = GeneratorTestHarness.Run(EntitySource);

        Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error);
        var handler = TreeText(result, "Crud.Create.Handler.g.cs");
        Assert.DoesNotContain("IRequestHandler", handler);
    }

    [Fact]
    public void SmartOverrideSkipsDeclaredHandlerAndEndpoint()
    {
        const string manual = """
            using Microsoft.AspNetCore.Builder;

            namespace Shop.Domain.Features.Categories;

            public sealed class DeleteCategoryHandler { }

            public static class DeleteCategoryEndpoint
            {
                public static Microsoft.AspNetCore.Builder.RouteHandlerBuilder Map(
                    Microsoft.AspNetCore.Routing.IEndpointRouteBuilder group,
                    System.Func<Microsoft.AspNetCore.Http.HttpContext, ClrinfCS.Core.RequestContext> contextFactory) =>
                    group.MapDelete("/{id}", () => Microsoft.AspNetCore.Http.Results.NoContent());
            }
            """;

        var (_, output, result, diagnostics, _) = GeneratorTestHarness.Run(EntitySource, additionalSources: manual);

        Assert.DoesNotContain(diagnostics, d => d.Severity == DiagnosticSeverity.Error);
        Assert.DoesNotContain(output.GetDiagnostics(), d => d.Severity == DiagnosticSeverity.Error);

        var hints = result.GeneratedTrees.Select(t => t.FilePath).ToArray();
        Assert.DoesNotContain(hints, h => h.Contains(".Crud.Delete.Handler.g.cs"));
        Assert.DoesNotContain(hints, h => h.Contains(".Crud.Delete.Endpoint.g.cs"));
        Assert.Contains(hints, h => h.Contains(".Crud.Create.Handler.g.cs"));
    }

    [Fact]
    public void MissingIdReportsClrCrud001()
    {
        const string source = """
            using ClrinfCS.Core;

            namespace Shop.Domain;

            [GenerateCrudEndpoints]
            public class Category
            {
                public string Name { get; set; } = string.Empty;
            }
            """;

        var (_, _, result, diagnostics, _) = GeneratorTestHarness.Run(source);

        Assert.Contains(result.Diagnostics, d => d.Id == "CLRCRUD001");
        Assert.Contains(diagnostics, d => d.Id == "CLRCRUD001");
    }

    [Fact]
    public void MediatorNetWithoutPackageReportsClrCrud003()
    {
        var source = EntitySource.Replace(
            "[GenerateCrudEndpoints]",
            "[GenerateCrudEndpoints(Dispatcher = CrudDispatcher.MediatorNet)]");

        var (_, _, result, _, _) = GeneratorTestHarness.Run(source);

        Assert.Contains(result.Diagnostics, d => d.Id == "CLRCRUD003");
        Assert.DoesNotContain(result.GeneratedTrees, t => t.FilePath.Contains("Crud.Create.Handler"));
    }

    [Fact]
    public void ExcludedOperationWithoutOverrideReportsClrCrud002()
    {
        var source = EntitySource.Replace(
            "[GenerateCrudEndpoints]",
            "[GenerateCrudEndpoints(Operations = CrudOperations.Create | CrudOperations.GetList)]");

        var (_, _, result, _, _) = GeneratorTestHarness.Run(source);

        Assert.Contains(result.Diagnostics, d => d.Id == "CLRCRUD002");
        Assert.DoesNotContain(result.GeneratedTrees, t => t.FilePath.Contains(".Crud.Delete.Handler"));
    }

    [Fact]
    public void SecuredEntitiesRequirePerOperationPolicy()
    {
        var (_, _, result, _, _) = GeneratorTestHarness.Run(EntitySource, securedProperty: "true");

        var endpoint = TreeText(result, "Crud.Create.Endpoint.g.cs");
        Assert.Contains("RequireAuthorization(\"category.create\")", endpoint);
        var central = TreeText(result, "GeneratedCrudExtensions.g.cs");
        Assert.Contains("categoryCrudGroup.RequireAuthorization()", central);
    }

    [Fact]
    public void SecondRunUsesCachedIncrementalOutputs()
    {
        var (input, _, _, _, driver) = GeneratorTestHarness.Run(EntitySource, trackSteps: true);

        var driver2 = GeneratorTestHarness.RunIncrementally(driver, input);
        var result = driver2.GetRunResult();

        var outputs = result.Results[0].TrackedOutputSteps
            .SelectMany(static kv => kv.Value)
            .SelectMany(static step => step.Outputs)
            .ToArray();

        Assert.Contains(outputs, static output => output.Reason == IncrementalStepRunReason.Cached);
    }

    private static string TreeText(GeneratorDriverRunResult result, string suffix)
    {
        var tree = result.GeneratedTrees.Single(t => t.FilePath.EndsWith(suffix, StringComparison.Ordinal));
        return tree.GetText().ToString();
    }
}
